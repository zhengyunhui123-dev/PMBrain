import json
import sys
from pathlib import Path
from urllib.parse import urlparse
from playwright.sync_api import sync_playwright, expect

url = sys.argv[1] if len(sys.argv) > 1 else 'http://127.0.0.1:5298/admin/'
target = urlparse(url)
assert target.hostname == '127.0.0.1' and target.port in [5298, 5398], '仅允许隔离预览端口 5298/5398'
output = Path('.codex/design-refresh')
output.mkdir(parents=True, exist_ok=True)
checks = []
errors = []
with sync_playwright() as playwright:
    browser = playwright.chromium.launch(channel='msedge', headless=True)
    page = browser.new_page(viewport={'width': 1440, 'height': 900}, permissions=['clipboard-read', 'clipboard-write'])
    page.on('pageerror', lambda error: errors.append(str(error)))
    try:
        page.goto(url + '#data')
        page.wait_for_load_state('networkidle')
        expect(page.get_by_role('row', name='查看 本周工作记录', exact=True)).to_be_visible()
        for tab, title in [('原始资料', '本周工作记录'), ('结构化知识', '把资料整理成知识'), ('观点与总结', '写作从一个具体问题开始')]:
            page.get_by_role('tab', name=tab, exact=True).click()
            expect(page.get_by_role('row', name='查看 ' + title, exact=True)).to_be_visible()
        page.get_by_role('tab', name='事实', exact=True).click()
        expect(page.get_by_role('tab', name='事实', exact=True)).to_have_attribute('aria-selected', 'true')
        page.get_by_role('tab', name='全部', exact=True).click()
        search = page.get_by_label('搜索知识', exact=True)
        search.fill('本周工作')
        expect(page.get_by_role('row', name='查看 本周工作记录', exact=True)).to_be_visible()
        expect(page.locator('.brain-page-table tbody tr')).to_have_count(1)
        search.fill('没有这样的测试内容')
        expect(page.locator('.library-empty')).to_contain_text('没有符合条件')
        search.fill('')
        page.get_by_label('类型筛选', exact=True).select_option('concept')
        expect(page.get_by_role('row', name='查看 把资料整理成知识', exact=True)).to_be_visible()
        expect(page.locator('.brain-page-table tbody tr')).to_have_count(1)
        page.get_by_label('类型筛选', exact=True).select_option('all')
        checks.append('真实API：分类、类型和标题搜索、空结果')
        page.get_by_role('row', name='查看 本周工作记录', exact=True).click()
        dialog = page.get_by_role('dialog', name='本周工作记录', exact=True)
        expect(dialog).to_contain_text('保留出处与上下文')
        for tab in ['观点与信息', '切片状态', 'Markdown 内容']:
            dialog.get_by_role('tab', name=tab, exact=True).click()
            expect(dialog.get_by_role('tab', name=tab, exact=True)).to_have_attribute('aria-selected', 'true')
        page.screenshot(path=str(output / 'library-document-dialog.png'))
        page.keyboard.press('Escape')
        expect(dialog).not_to_be_visible()
        page.get_by_role('row', name='查看 本周工作记录', exact=True).click()
        page.once('dialog', lambda prompt: prompt.dismiss())
        page.get_by_role('button', name='移出知识库', exact=True).click()
        expect(dialog).to_be_visible()
        page.once('dialog', lambda prompt: prompt.accept())
        page.get_by_role('button', name='移出知识库', exact=True).click()
        expect(dialog).not_to_be_visible()
        page.get_by_role('tab', name='回收站', exact=True).click()
        page.get_by_role('row', name='查看 本周工作记录', exact=True).click()
        page.get_by_role('button', name='撤销删除', exact=True).click()
        expect(dialog).not_to_be_visible()
        page.get_by_role('tab', name='全部', exact=True).click()
        expect(page.get_by_role('row', name='查看 本周工作记录', exact=True)).to_be_visible()
        checks.append('真实API：文档三页签、Escape、移出取消/确认及回收站恢复')
        page.goto(url + '#assistant')
        page.wait_for_load_state('networkidle')
        expect(page.get_by_label('助手回答').last).to_contain_text('隔离测试回复')
        page.get_by_label('更多操作', exact=True).click()
        page.get_by_role('button', name='复制全部对话', exact=True).click()
        copied = page.evaluate('navigator.clipboard.readText()')
        assert '验证首页提问' in copied and '隔离测试回复' in copied
        page.get_by_label('更多操作', exact=True).click()
        page.keyboard.press('Escape')
        expect(page.locator('.wb-more')).not_to_have_attribute('open', '')
        page.get_by_label('更多操作', exact=True).click()
        page.locator('.wb-workspace-label').click()
        expect(page.locator('.wb-more')).not_to_have_attribute('open', '')
        checks.append('真实对话：复制全部内容、更多菜单Escape和点击外部关闭')
        notice_close = page.get_by_role('button', name='关闭任务通知', exact=True)
        if notice_close.count():
            notice_close.click()
        composer = page.locator('.knowledge-workbench .wb-composer')
        attachment = {'name': 'design-preview.txt', 'mimeType': 'text/plain', 'buffer': b'Isolated attachment for desktop UI validation.'}
        with page.expect_file_chooser() as chooser:
            page.get_by_role('button', name='添加附件', exact=True).click()
        chooser.value.set_files(attachment)
        expect(composer).to_contain_text('design-preview.txt')
        composer.get_by_role('button', name='移除 design-preview.txt', exact=True).click()
        expect(composer.locator('.wb-attachments')).not_to_be_visible()
        page.locator('.knowledge-workbench input[type="file"]').set_input_files(attachment)
        message = page.get_by_role('textbox', name='消息', exact=True)
        message.fill('验证附件随问题一起发送')
        answer_count = page.get_by_label('助手回答').count()
        page.get_by_role('button', name='发送消息', exact=True).click()
        expect(page.get_by_label('助手回答')).to_have_count(answer_count + 1)
        expect(page.get_by_label('你的消息').last).to_contain_text('design-preview.txt')
        answer = page.get_by_label('助手回答').last
        expect(answer).to_contain_text('隔离测试回复', timeout=30000)
        answer.get_by_role('button', name='复制', exact=True).click()
        assert '隔离测试回复' in page.evaluate('navigator.clipboard.readText()')
        page.get_by_label('你的消息').last.get_by_role('button', name='修改问题', exact=True).click()
        expect(message).to_have_value('验证附件随问题一起发送')
        message.fill('验证修改问题后重新回答')
        page.get_by_role('button', name='发送消息', exact=True).click()
        expect(page.get_by_label('你的消息').last).to_contain_text('验证修改问题后重新回答')
        expect(page.get_by_label('助手回答').last).to_contain_text('隔离测试回复', timeout=30000)
        page.reload()
        expect(page.get_by_label('你的消息').last).to_contain_text('验证修改问题后重新回答')
        checks.append('真实对话：附件添加/移除/发送、单条复制、修改问题及重载保留')
        page.get_by_role('button', name='助手配置', exact=True).click()
        config = page.get_by_role('dialog', name='助手配置', exact=True)
        expect(config).to_have_css('width', '820px')
        expect(config.locator('.wb-assistant-form')).to_have_css('overflow-y', 'auto')
        for tab in ['职责与规则', '技能', '资料', '定时任务', '概览']:
            config.get_by_role('button', name=tab, exact=True).click()
            expect(config).to_be_visible()
        page.screenshot(path=str(output / 'assistant-config-dialog.png'))
        config.get_by_role('button', name='职责与规则', exact=True).click()
        page.get_by_label('助手职责', exact=True).fill('按用户要求查询资料，并保留资料出处。')
        config.get_by_role('button', name='保存', exact=True).click()
        expect(config).not_to_be_visible()
        page.reload()
        page.wait_for_load_state('networkidle')
        page.get_by_role('button', name='助手配置', exact=True).click()
        config.get_by_role('button', name='职责与规则', exact=True).click()
        expect(page.get_by_label('助手职责', exact=True)).to_have_value('按用户要求查询资料，并保留资料出处。')
        page.keyboard.press('Escape')
        expect(config).not_to_be_visible()
        checks.append('真实API：助手配置五分类、保存和重载保留')
        for route, card in [('data', '知识库'), ('graph', '知识图谱'), ('dream', '知识整理'), ('dashboard', '总体概览'), ('mcp', 'MCP 接入')]:
            page.goto(url + '#home')
            page.locator('.home-actions .home-card').filter(has=page.get_by_text(card, exact=True)).click()
            expect(page).to_have_url(url + '#' + route)
        page.goto(url + '#home')
        page.locator('.home-actions .home-card').filter(has=page.get_by_text('导入资料', exact=True)).click()
        expect(page.get_by_role('dialog')).to_be_visible()
        checks.append('首页六个快捷入口均接现有页面或导入弹窗')
        assert not errors, errors
        (output / 'interaction-receipt.json').write_text(json.dumps({'checks': checks, 'pageErrors': errors}, ensure_ascii=False, indent=2), encoding='utf-8')
    except Exception:
        page.screenshot(path=str(output / 'interaction-failure.png'))
        (output / 'interaction-failure.txt').write_text(page.locator('body').inner_text(), encoding='utf-8')
        raise
    finally:
        browser.close()
print(json.dumps({'checks': len(checks), 'pageErrors': errors}, ensure_ascii=False))
